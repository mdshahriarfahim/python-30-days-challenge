# 4.1 - Arithmetic Operators


'''
+ - Addition         (5 + 3 = 8)
- - Subtraction      (5 - 3 = 2)
* - Multiplication   (5 * 3 = 15)
/ - Division         (5 / 3 = 1.666...)
% - Modulus          (5 % 3 = 2)
** - Exponentiation   (5 ** 3 = 125)
// - Floor Division   (5 // 3 = 1)

'''



num1 = 10
num2 = 3
print(num1 + num2)  # Addition
print(num1 - num2)  # Subtraction
print(num1 * num2)  # Multiplication
print(num1 / num2)  # Division


