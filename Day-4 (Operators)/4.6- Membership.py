# 4.6 - Membership Operators

'''
in - Returns True if a sequence with the specified value is present in the object
(5 in [1, 2, 3, 4, 5] = True)

not in - Returns True if a sequence with the specified value is not present in the object
(5 not in [1, 2, 3, 4, 5] = True)

'''






print("check 'a' in 'Python' : ", 'a' in 'Python')  # Output: False
print("check 'P' in 'Python' : ", 'P' in 'Python')  # Output: True
print("check 'y' not in 'Python' : ", 'y' not in 'Python')  # Output: False
print("check 'z' not in 'Python' : ", 'z' not in 'Python')  # Output: True


