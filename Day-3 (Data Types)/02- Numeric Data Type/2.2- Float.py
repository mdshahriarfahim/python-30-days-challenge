#2.2 Float - Decimal Number

order_price = 10.5
print("Order Price is", type(order_price))
print("Order Price is", order_price)


order_discount = 2.5
print("Order Discount is", type(order_discount))
print("Order Discount is", order_discount)


order_tax = 1.5
print("Order Tax is", type(order_tax))
print("Order Tax is", order_tax)

order_total = order_price + order_discount + order_tax
print("Order Total is", type(order_total))
print("Order Total is", order_total)